export function icono(nombre: keyof typeof MAPAS | string, acento = 'currentColor') {
  const m = MAPAS[nombre];
  let rects = '';
  m.forEach((fila, y) => [...fila].forEach((ch, x) => {
    if (ch === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    else if (ch === 'o') rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${acento}"/>`;
  }));
  return `<svg class="icono" viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
